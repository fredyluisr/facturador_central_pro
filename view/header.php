    <script>
    document.addEventListener('DOMContentLoaded', function () {
        window.setTimeout(function () {
            var currentPage = (window.location.pathname.split('/').pop() || '').toLowerCase();
            document.querySelectorAll('#sidebar-menu a[href]').forEach(function (link) {
                var rawHref = link.getAttribute('href');
                if (!rawHref || rawHref === '#' || rawHref.indexOf('javascript:') === 0) return;
                var linkPage = rawHref.split('?')[0].split('#')[0].split('/').pop().toLowerCase();
                if (linkPage !== currentPage) return;

                link.classList.add('active');
                var submenuList = link.closest('ul.nav-dropdown-items');
                if (!submenuList) return;
                var submenu = submenuList.closest('li.submenu');
                if (submenu) {
                    document.querySelectorAll('#sidebar-menu li.submenu > ul').forEach(function (list) {
                        if (list !== submenuList) list.style.display = 'none';
                    });
                    document.querySelectorAll('#sidebar-menu li.submenu > a').forEach(function (item) {
                        if (item !== submenu.querySelector(':scope > a')) item.classList.remove('subdrop', 'active');
                    });
                    submenuList.style.display = 'block';
                    var trigger = submenu.querySelector(':scope > a');
                    if (trigger) trigger.classList.add('subdrop', 'active');
                }
            });
        }, 120);
    });
    </script>

